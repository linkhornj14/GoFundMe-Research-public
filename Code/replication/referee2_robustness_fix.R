r_camp <- wcr_p(weekCamp,  ".lc",  controls = C1, B = B)
r_fe   <- wcr_p(weekLabel, ".lfe", controls = C2, B = B)
r_biz  <- wcr_p(weekLabel, ".lbiz",controls = C2, B = B)
r_d3   <- wcr_p(official,  ".lfe", controls = C2, B = B)

