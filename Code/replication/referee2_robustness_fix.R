## ---- (M4) Honest DiD --------------------------------------------------------
cat("\nRunning HonestDiD...\n")
weekCamp_es <- weekCamp %>%
  filter(year == "2020", !is.na(fWeek), !is.na(fWeek1End)) %>%
  mutate(time2treat = as.integer(week) - as.integer(fWeek),
         post_boundary = as.integer(fWeek1End) - as.integer(fWeek)) %>%
  filter(time2treat >= -12, time2treat <= post_boundary)
es_total <- feols(log(campaigns) ~ i(time2treat, ref = -1) +
                    cases + initial_claims + insured_unemployment_rate +
                    continued_claims + puaIC | state + week,
                  cluster = ~state, weights = ~total_population, data = weekCamp_es)

honest_ok <- FALSE
honest_tab <- NULL
if (requireNamespace("HonestDiD", quietly = TRUE)) {
  res <- tryCatch({
    es_terms <- grep("^time2treat::", names(coef(es_total)), value = TRUE)
    es_lags  <- as.integer(gsub("^time2treat::", "", es_terms))
    ord <- order(es_lags); es_terms <- es_terms[ord]; es_lags <- es_lags[ord]
    betahat <- unname(coef(es_total)[es_terms])
    sigma   <- unname(vcov(es_total)[es_terms, es_terms, drop = FALSE])
    sigma   <- (sigma + t(sigma)) / 2
    keep <- !is.na(betahat)
    betahat <- betahat[keep]; sigma <- sigma[keep, keep, drop = FALSE]; es_lags <- es_lags[keep]
    HonestDiD::createSensitivityResults_relativeMagnitudes(
      betahat = betahat, sigma = sigma,
      numPrePeriods = sum(es_lags < 0), numPostPeriods = sum(es_lags >= 0),
      Mbarvec = c(0.5, 1, 1.5, 2))
  }, error = function(e) { cat("   HonestDiD error:", conditionMessage(e), "\n"); NULL })
  if (!is.null(res)) {
    honest_ok <- TRUE
    honest_tab <- data.frame(Mbar = res$Mbar, lb = res$lb, ub = res$ub)
    print(honest_tab, digits = 4)
    hd <- c("% Generated by Code/replication/referee2_robustness_fix.R",
            "\\begingroup", "\\centering", "\\begin{tabular}{rrr}", "\\toprule",
            "$\\bar{M}$ & Lower bound & Upper bound \\\\", "\\midrule",
            paste0(formatC(honest_tab$Mbar, format="f", digits=1), " & ",
                   formatC(honest_tab$lb, format="f", digits=4), " & ",
                   formatC(honest_tab$ub, format="f", digits=4), " \\\\"),
            "\\bottomrule",
            "\\multicolumn{3}{l}{\\footnotesize{Relative-magnitudes bounds (Rambachan-Roth 2023) on the event-study ATT.}}",
            "\\end{tabular}", "\\par\\endgroup")
    writeLines(hd, file.path(tab_dir, "honest_did.tex"))
    cat("Wrote honest_did.tex\n")
  }
}

## ---- emit the macro values to patch into inline_stats.tex ------------------
fmt_p <- function(p) if (is.na(p)) "??" else if (p < 0.001) "$<$0.001" else formatC(p, format="f", digits=3)
cat("\n==== MACRO VALUES ====\n")
cat("wildPFinEmerg =", fmt_p(r_fe$p_boot), "\n")
cat("wildPBusiness =", fmt_p(r_biz$p_boot), "\n")
if (honest_ok) {
  i1 <- which(honest_tab$Mbar == 1)
  cat("honestDidLowerMone =", formatC(honest_tab$lb[i1], format="f", digits=4), "\n")
  cat("honestDidUpperMone =", formatC(honest_tab$ub[i1], format="f", digits=4), "\n")
}
cat("======================\n")
