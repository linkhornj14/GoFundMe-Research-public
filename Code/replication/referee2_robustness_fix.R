## referee2_robustness_fix.R
## Populates the two robustness pieces that were unpopulated in the manuscript:
##   (M2) Wild cluster bootstrap p-values  -> paper/tables/wild_bootstrap.tex
##   (M4) Honest DiD (Rambachan-Roth 2023)  -> paper/tables/honest_did.tex
## and prints the macro values so paper/inline_stats.tex can be updated.
##
## fwildclusterboot is unavailable for R 4.4.2, so the wild cluster bootstrap is
## implemented manually: restricted (null-imposed) Rademacher WCR, clustered on
## state, matching Cameron-Gelbach-Miller (2008). Results are sanity-checked
## against the asymptotic cluster-robust p-values.
##
## Run:  Rscript Code/replication/referee2_robustness_fix.R

suppressPackageStartupMessages({ library(fixest); library(tidyverse); library(here) })

set.seed(20260514)
B <- 2999

load(here::here(".RData"))
weekCamp  <- ungroup(weekCamp)
weekLabel <- ungroup(weekLabel)
tab_dir <- here::here("paper", "tables")

C1 <- c("median_income","percent_poverty","cases","initial_claims",
        "insured_unemployment_rate","continued_claims","puaIC")
C2 <- c("median_income","cases","initial_claims",
        "insured_unemployment_rate","continued_claims","puaIC")

## ---- manual restricted (null-imposed) WCR Rademacher bootstrap -------------
wcr_p <- function(data, yvar, treat = "treat", controls, cluster = "state", B = 2999) {
  d <- data
  d$.y <- d[[yvar]]
  fe <- "state + year^week"
  full_f <- as.formula(paste0(".y ~ ", treat, " + ", paste(controls, collapse=" + "),
                              " | ", fe))
  rest_f <- as.formula(paste0(".y ~ ", paste(controls, collapse=" + "), " | ", fe))
  m_full <- feols(full_f, data = d, weights = ~total_population, cluster = stats::reformulate(cluster))
  t_obs  <- coef(m_full)[treat] / sqrt(diag(vcov(m_full)))[treat]
  m_rest <- feols(rest_f, data = d, weights = ~total_population)
  fit0 <- predict(m_rest); res0 <- resid(m_rest)
  cl   <- d[[cluster]]
  gnames <- unique(cl)
  tstar <- numeric(B)
  for (b in seq_len(B)) {
    w <- sample(c(-1, 1), length(gnames), replace = TRUE)
    names(w) <- gnames
    d$.y <- fit0 + w[as.character(cl)] * res0
    mb <- feols(full_f, data = d, weights = ~total_population,
                cluster = stats::reformulate(cluster))
    tstar[b] <- coef(mb)[treat] / sqrt(diag(vcov(mb)))[treat]
  }
  p_boot  <- (1 + sum(abs(tstar) >= abs(t_obs))) / (B + 1)
  p_asym  <- fixest::pvalue(m_full)[treat]
  list(p_boot = unname(p_boot), p_asym = unname(p_asym), t_obs = unname(t_obs))
}

cat("Running wild cluster bootstrap (B =", B, ")...\n")
weekCamp$.lc  <- log(weekCamp$campaigns)
