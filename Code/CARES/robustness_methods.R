## robustness_methods.R
## Alternative-methodology robustness battery for the GoFundMe/UI paper.
## Addresses the audit's central concern (identifying variation vs. headline
## outcome do not overlap in time) and the non-absorbing composite treatment.
##
## Sections:
##   A. Callaway-Sant'Anna (2021) DR DiD on the 2021 FPUC-$300 staggered
##      termination ("benefits off"); selection handled via xformla (1a).
##   B. MatchIt/IPW 2x2 DiD cross-check of A (1a, transparency).
##   C. de Chaisemartin-D'Haultfoeuille did_multiplegt_dyn on the non-absorbing
##      composite treat, extensive margin (2a).
##   D. Program-specific FPUC600/LWA/FPUC300 indicators on counts (2b).
##   E. Treatment-timing selection/balance diagnostic (Tier 2, 4a).
##   F. Randomization inference for the 1a ATT (Tier 2, 4b).
##   G. Honest DiD retry on the termination event study (Tier 2, 3b).
##
## Each section is wrapped in tryCatch so one failure does not abort the run.
## Run:  Rscript Code/CARES/robustness_methods.R   (after build_fpuc300_termination.R)

suppressPackageStartupMessages({
  library(tidyverse); library(here); library(fixest)
  library(did); library(MatchIt)
})
set.seed(20260622)

exp_dir <- here::here("Code", "replication", "exported")
tab_dir <- here::here("paper", "tables")
fig_dir <- here::here("paper", "figures")
dir.create(tab_dir, recursive = TRUE, showWarnings = FALSE)
dir.create(fig_dir, recursive = TRUE, showWarnings = FALSE)

panel_w <- readr::read_csv(file.path(exp_dir, "panel_termination_2021.csv"),
                           show_col_types = FALSE)

## Aggregate weekly -> monthly to reduce sparsity (weekly counts average ~1.75,
## too thin for the CS group-time cells). Termination binned to month: June
## (<= ISO wk 26) vs July+ (wk 27-31); gmonth = 0 for never-early controls.
panel <- panel_w %>%
  mutate(month = pmin(12L, as.integer(ceiling(week / 4.345)))) %>%
  group_by(state, state_id, month, early, term_week) %>%
  summarize(across(c(num_financial_emergency, num_business, campaigns,
                     donationsTotal, amountTotal), sum),
            across(c(median_income, percent_poverty, total_population,
                     insured_unemployment_rate), first), .groups = "drop") %>%
  mutate(gmonth = if_else(early, pmin(12L, as.integer(ceiling(term_week / 4.345))), 0L))

writetab <- function(lines, file) { writeLines(lines, file.path(tab_dir, file))
  cat("      Saved:", file, "\n") }

## ===========================================================================
## A. Callaway-Sant'Anna DiD on 2021 FPUC-$300 termination (monthly, IPW).
##    IPW reweights treated/control via a propensity model on baseline
##    observables -- the requested selection-on-observables handling. DR/reg
##    are numerically unstable here (a near-singleton July cohort), so IPW is
##    the reported estimator.
## ===========================================================================
cat("[A] Callaway-Sant'Anna termination DiD (monthly, IPW)...\n")
cs_results <- list()
run_cs <- function(yname, data = panel, label = yname) {
  att <- att_gt(
    yname = yname, tname = "month", idname = "state_id", gname = "gmonth",
    xformla = ~ percent_poverty + median_income,
    data = as.data.frame(data), control_group = "nevertreated",
    est_method = "ipw"
  )
  list(simple = aggte(att, type = "simple", na.rm = TRUE),
       dynamic = aggte(att, type = "dynamic", na.rm = TRUE),
       att = att)
}
for (yv in c("num_financial_emergency", "campaigns", "amountTotal")) {
  cs_results[[yv]] <- tryCatch(run_cs(yv),
    error = function(e) { cat("      CS", yv, "failed:", conditionMessage(e), "\n"); NULL })
}

## Sensitivity: drop the two states whose panel termination status disagrees
## with the public record (VT flagged early but not in public list; NH the
## reverse). See build_fpuc300_termination.R cross-check.
cs_sens <- tryCatch(run_cs("num_financial_emergency",
                           data = dplyr::filter(panel, !state %in% c("VT","NH"))),
  error = function(e) { cat("      CS sensitivity failed:", conditionMessage(e), "\n"); NULL })

## Build the CS results table
