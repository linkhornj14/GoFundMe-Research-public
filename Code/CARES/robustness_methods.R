## ===========================================================================
## B. IPW-weighted 2x2 DiD cross-check (transparent, robust to the 26>24
##    treated/control imbalance that breaks 1:1 matching). Propensity from a
##    baseline-observables logit; ATT weights; DiD around the June termination.
## ===========================================================================
cat("[B] IPW-weighted DiD cross-check...\n")
tryCatch({
  base_cov <- panel %>% group_by(state, state_id) %>%
    summarize(early = as.integer(first(early)),
              median_income = first(median_income),
              percent_poverty = first(percent_poverty),
              total_population = first(total_population), .groups = "drop")
  ## propensity score for early termination on baseline observables
  ps <- glm(early ~ scale(median_income) + scale(percent_poverty) + scale(total_population),
            family = binomial, data = base_cov)
  base_cov$pscore <- predict(ps, type = "response")
  ## ATT weights: treated = 1, control = p/(1-p)
  base_cov <- base_cov %>%
    mutate(ipw = if_else(early == 1, 1, pscore / pmax(1 - pscore, 1e-3)))
  did_dat <- panel %>%
    left_join(base_cov %>% select(state, early2 = early, ipw), by = "state") %>%
    mutate(post = as.integer(month >= 6), treatpost = early2 * post)
  ## also combine the population weight with the IPW weight
  did_dat$w <- did_dat$ipw * did_dat$total_population
  m_did <- feols(num_financial_emergency ~ post + treatpost | state_id,
                 cluster = ~state_id, weights = ~w, data = did_dat)
  ips <- c("% Generated by Code/CARES/robustness_methods.R [B]",
           "\\begingroup\\centering\\begin{tabular}{lcc}", "\\toprule",
           "Interaction (early $\\times$ post) & Estimate & Std. err. \\\\", "\\midrule",
           sprintf("IPW-weighted DiD (fin. emergency count) & %0.4f & %0.4f \\\\",
                   coef(m_did)["treatpost"], sqrt(diag(vcov(m_did)))["treatpost"]),
           "\\bottomrule",
           "\\multicolumn{3}{l}{\\footnotesize{Inverse-propensity (ATT) weighted on baseline income, poverty, population $\\times$ population weight.}}",
           "\\end{tabular}\\par\\endgroup")
  writetab(ips, "matched_did.tex")
  cat("      IPW DiD interaction:", round(coef(m_did)["treatpost"], 4), "\n")
}, error = function(e) cat("      IPW DiD section failed:", conditionMessage(e), "\n"))

cat("[A/B] done.\n")

## ===========================================================================
## Load full 2020-2021 panels for the switching-treatment and program-specific
## analyses (sections C, D) and the balance/RI diagnostics.
