    row1(cs_results[["num_financial_emergency"]], "Financial emergency (count)"),
    if (!is.null(cs_results[["campaigns"]])) row1(cs_results[["campaigns"]], "All campaigns (count)"),
    if (!is.null(cs_results[["amountTotal"]])) row1(cs_results[["amountTotal"]], "Total amount raised"),
    if (!is.null(cs_sens)) row1(cs_sens, "Fin. emerg. (excl. VT, NH)"),
    "\\bottomrule",
    "\\multicolumn{4}{l}{\\footnotesize{Callaway-Sant'Anna (2021) ATT, inverse-propensity weighted on baseline poverty}}\\\\",
    "\\multicolumn{4}{l}{\\footnotesize{and median income; never-treated controls; monthly. Treatment = early FPUC-\\$300 termination.}}",
    "\\end{tabular}\\par\\endgroup")
