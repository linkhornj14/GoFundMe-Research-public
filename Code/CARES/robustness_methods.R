load(here::here(".RData"))
weekLabel <- ungroup(weekLabel); weekCamp <- ungroup(weekCamp)
## continuous week index across 2020-2021 and program indicators
mk_time <- function(df) df %>%
  mutate(yr = as.integer(as.character(year)),
         twave = (yr - 2020L) * 53L + as.integer(week),
         fpuc600 = as.integer((week >= fWeek & week <= fWeek1End) & yr == 2020),
         lwa     = as.integer((week >= lWeekStart & week <= lWeekEnd) & !is.na(lWeekStart) & yr == 2020),
         fpuc300 = as.integer((week >= fWeek2 & week <= fWeek2End) & yr == 2021)) %>%
  mutate(across(c(fpuc600, lwa, fpuc300), ~ replace_na(.x, 0L)))
wL <- mk_time(weekLabel)
wC <- mk_time(weekCamp)
wC$state_id <- as.integer(factor(wC$state))
wL$state_id <- as.integer(factor(wL$state))

## ===========================================================================
## C. de Chaisemartin-D'Haultfoeuille switching-treatment estimator. Correct
##    tool for the NON-ABSORBING composite `treat` (Sun-Abraham/CS assume
##    absorbing adoption). Extensive margin (counts). Dynamic + placebo.
## ===========================================================================
## Implemented in Stata, not here: the R DYN package needs `polars`, which
## will not build on this Windows/R 4.4.2 setup, and DIDmultiplegt's
## did_multiplegt_old returns non-finite estimates on these sparse weekly
## counts. Stata's did_multiplegt_dyn runs episode by episode (FPUC-600 onset,
## LWA onset, FPUC-300 early termination), the only staggered switches in
## `treat`. Paper: sec:dcdh.
##   Stata:  StataMP-64 /e do Code/CARES/dcdh_episodes.do
##   Table:  Rscript Code/CARES/dcdh_table.R  -> paper/tables/dcdh_episodes.tex
cat("[C] de Chaisemartin estimator: run Code/CARES/dcdh_episodes.do (Stata),",
    "then Code/CARES/dcdh_table.R.\n")

## ===========================================================================
## D. Program-specific indicators (FPUC600 / LWA / FPUC300) on counts.
##    Currently the paper only does this for goal amounts (diff4). Extensive
##    margin here. Separates the blended ITF `treat` into its components.
## ===========================================================================
cat("[D] Program-specific indicators on counts...\n")
tryCatch({
  prog <- function(df, yv) feols(
    as.formula(paste0("log(", yv, " + 1) ~ fpuc600 + lwa + fpuc300 + median_income +",
                      "cases + initial_claims + insured_unemployment_rate + continued_claims + puaIC",
                      "| state + year^week")),
    cluster = ~state, weights = ~total_population, data = df)
  p_fe  <- prog(wL, "num_financial_emergency")
  p_biz <- prog(wL, "num_business")
  p_all <- prog(wC, "campaigns")
  etable(list("Fin. Emergency" = p_fe, "Business" = p_biz, "All campaigns" = p_all),
         keep = c("%fpuc600", "%lwa", "%fpuc300"),
         dict = c(fpuc600 = "FPUC-$600", lwa = "LWA", fpuc300 = "FPUC-$300"),
         title = "Program-Specific Effects on Campaign Counts",
         style.tex = style.tex("aer"), fitstat = ~ r2 + n,
         file = file.path(tab_dir, "program_specific.tex"), replace = TRUE)
  cat("      Saved: program_specific.tex (fpuc600 fe coef",
      round(coef(p_fe)["fpuc600"], 4), ")\n")
}, error = function(e) cat("      Program-specific section failed:", conditionMessage(e), "\n"))

## ===========================================================================
## E. Treatment-timing selection / balance diagnostic (Tier 2, 4a).
##    Regress early-termination status and termination week on baseline
##    observables -> characterizes selection-into-treatment.
## ===========================================================================
cat("[E] Treatment-timing balance diagnostic...\n")
tryCatch({
  bc <- panel %>% group_by(state) %>%
    summarize(early = as.integer(first(gmonth > 0)),
              term_week = first(term_week),
              median_income = first(median_income),
              percent_poverty = first(percent_poverty),
              total_population = first(total_population), .groups = "drop")
  bm <- lm(early ~ scale(median_income) + scale(percent_poverty) + scale(total_population), data = bc)
  ct <- summary(bm)$coefficients
  rn <- c("Median income", "Poverty rate", "Population")
  bl <- c("% Generated by Code/CARES/robustness_methods.R [E]",
          "\\begingroup\\centering\\begin{tabular}{lcc}", "\\toprule",
          "Baseline covariate (standardized) & Coef. on Pr(early term.) & Std. err. \\\\", "\\midrule",
          sprintf("%s & %0.4f & %0.4f \\\\", rn, ct[2:4, 1], ct[2:4, 2]),
          "\\bottomrule",
          "\\multicolumn{3}{l}{\\footnotesize{LPM of early FPUC-\\$300 termination on standardized baseline observables.}}",
          "\\end{tabular}\\par\\endgroup")
  writetab(bl, "balance_timing.tex")
  cat("      Balance: poverty coef on Pr(early) =", round(ct[3, 1], 4), "\n")
}, error = function(e) cat("      Balance section failed:", conditionMessage(e), "\n"))

## ===========================================================================
## F. Randomization inference for the 1a ATT (Tier 2, 4b). Permute early-
##    termination assignment across states; recompute the IPW DiD interaction;
##    design-based p-value robust to 50 clusters + switching.
## ===========================================================================
cat("[F] Randomization inference...\n")
tryCatch({
  obs_int <- coef(feols(num_financial_emergency ~ post + treatpost | state_id,
                        weights = ~total_population,
                        data = panel %>% mutate(post = as.integer(month >= 6),
                                                treatpost = as.integer(early) * post)))["treatpost"]
  states <- unique(panel$state); n_early <- n_distinct(panel$state[panel$early])
  B <- 1000; perm <- numeric(B)
  for (b in seq_len(B)) {
    fake_early <- sample(states, n_early)
    d <- panel %>% mutate(e = as.integer(state %in% fake_early),
                          post = as.integer(month >= 6), tp = e * post)
    perm[b] <- coef(feols(num_financial_emergency ~ post + tp | state_id,
                          weights = ~total_population, data = d))["tp"]
  }
  p_ri <- (1 + sum(abs(perm) >= abs(obs_int))) / (B + 1)
  ri <- c("% Generated by Code/CARES/robustness_methods.R [F]",
          "\\begingroup\\centering\\begin{tabular}{lc}", "\\toprule",
          "Quantity & Value \\\\", "\\midrule",
          sprintf("Observed DiD interaction & %0.4f \\\\", obs_int),
          sprintf("Randomization-inference $p$-value & %0.4f \\\\", p_ri),
          sprintf("Permutations & %d \\\\", B),
          "\\bottomrule",
          "\\multicolumn{2}{l}{\\footnotesize{Treatment timing reassigned across states; two-sided design-based $p$.}}",
          "\\end{tabular}\\par\\endgroup")
  writetab(ri, "randinf.tex")
  cat("      RI p-value:", round(p_ri, 4), "\n")
}, error = function(e) cat("      RI section failed:", conditionMessage(e), "\n"))

## ===========================================================================
## G. Honest DiD on the termination event study (Tier 2, 3b). Retry the
##    package with the smaller, balanced termination event window (the FPUC-600
##    event study triggered an internal symmetry failure in the audit).
## ===========================================================================
cat("[G] Honest DiD on termination event study...\n")
tryCatch({
  ## simple fixest event study around June termination, monthly
  es_dat <- panel %>% mutate(rel = month - 6L)            # event time vs June
  es <- feols(num_financial_emergency ~ i(rel, early, ref = -1) | state_id + month,
              cluster = ~state_id, data = es_dat)
  if (requireNamespace("HonestDiD", quietly = TRUE)) {
    terms <- grep("^rel::", names(coef(es)), value = TRUE)
    lags <- as.integer(sub("^rel::(-?[0-9]+):early", "\\1", terms))
    ord <- order(lags); terms <- terms[ord]; lags <- lags[ord]
    bh <- unname(coef(es)[terms]); S <- unname(vcov(es)[terms, terms, drop = FALSE])
    S <- (S + t(S)) / 2
    keep <- !is.na(bh); bh <- bh[keep]; S <- S[keep, keep, drop = FALSE]; lags <- lags[keep]
    hd <- HonestDiD::createSensitivityResults_relativeMagnitudes(
      betahat = bh, sigma = S, numPrePeriods = sum(lags < 0),
      numPostPeriods = sum(lags >= 0), Mbarvec = c(0.5, 1, 1.5, 2))
    ht <- c("% Generated by Code/CARES/robustness_methods.R [G]",
            "\\begingroup\\centering\\begin{tabular}{rrr}", "\\toprule",
            "$\\bar{M}$ & Lower bound & Upper bound \\\\", "\\midrule",
            sprintf("%0.1f & %0.4f & %0.4f \\\\", hd$Mbar, hd$lb, hd$ub),
            "\\bottomrule",
            "\\multicolumn{3}{l}{\\footnotesize{Rambachan-Roth (2023) relative-magnitudes bounds, FPUC-\\$300 termination event study.}}",
            "\\end{tabular}\\par\\endgroup")
    writetab(ht, "honest_did_termination.tex")
    cat("      HonestDiD Mbar=1 bound: [", round(hd$lb[hd$Mbar==1],3), ",", round(hd$ub[hd$Mbar==1],3), "]\n")
  }
}, error = function(e) cat("      HonestDiD section failed:", conditionMessage(e), "\n"))

cat("\n[done] All robustness sections complete.\n")
